import { PageHeader } from "@/components/PageHeader";
import { useTransactions, getStaffStats, STAFF_MEMBERS, getToday } from "@/lib/store";
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Cell } from "recharts";
import { motion } from "framer-motion";
import { useMemo, useState } from "react";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Trophy, TrendingUp } from "lucide-react";

const COLORS = [
  "hsl(350, 45%, 55%)",
  "hsl(35, 60%, 60%)",
  "hsl(152, 60%, 42%)",
  "hsl(210, 80%, 55%)",
  "hsl(280, 55%, 55%)",
  "hsl(20, 70%, 50%)",
];

function fmt(n: number) {
  return `₹${n.toLocaleString('en-IN')}`;
}

export default function Staff() {
  const { transactions } = useTransactions();
  const today = getToday();
  const [period, setPeriod] = useState<'today' | 'month' | 'all'>('all');

  const filtered = useMemo(() => {
    if (period === 'today') return transactions.filter(t => t.date === today);
    if (period === 'month') {
      const m = today.slice(0, 7);
      return transactions.filter(t => t.date.startsWith(m));
    }
    return transactions;
  }, [transactions, period, today]);

  const stats = useMemo(() => getStaffStats(filtered), [filtered]);
  const totalRevenue = stats.reduce((s, st) => s + st.revenue, 0);

  return (
    <div>
      <PageHeader title="Staff Performance" description="Track revenue generated by each team member" />

      <div className="mb-6 flex items-center gap-4">
        <Select value={period} onValueChange={v => setPeriod(v as typeof period)}>
          <SelectTrigger className="w-40"><SelectValue /></SelectTrigger>
          <SelectContent>
            <SelectItem value="today">Today</SelectItem>
            <SelectItem value="month">This Month</SelectItem>
            <SelectItem value="all">All Time</SelectItem>
          </SelectContent>
        </Select>
        <div className="flex items-center gap-2 text-sm text-muted-foreground">
          <TrendingUp className="h-4 w-4" />
          Total: {fmt(totalRevenue)}
        </div>
      </div>

      <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="stat-card mb-8">
        <h3 className="mb-4 font-display text-lg font-semibold">Revenue by Staff</h3>
        {stats.length === 0 ? (
          <p className="text-muted-foreground text-sm text-center py-12">No data for this period.</p>
        ) : (
          <ResponsiveContainer width="100%" height={320}>
            <BarChart data={stats} layout="vertical" margin={{ left: 20 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="hsl(30,15%,90%)" />
              <XAxis type="number" tick={{ fontSize: 12 }} stroke="hsl(20,10%,50%)" />
              <YAxis type="category" dataKey="name" tick={{ fontSize: 13 }} stroke="hsl(20,10%,50%)" width={80} />
              <Tooltip formatter={(v: number) => fmt(v)} />
              <Bar dataKey="revenue" radius={[0, 6, 6, 0]} barSize={28}>
                {stats.map((_, i) => (
                  <Cell key={i} fill={COLORS[i % COLORS.length]} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        )}
      </motion.div>

      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {stats.map((s, i) => (
          <motion.div
            key={s.name}
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: i * 0.05 }}
            className="stat-card flex items-center gap-4"
          >
            {i === 0 && <Trophy className="h-6 w-6 text-accent" />}
            <div>
              <p className="font-display text-lg font-semibold text-foreground">{s.name}</p>
              <p className="text-2xl font-bold text-primary">{fmt(s.revenue)}</p>
              <p className="text-xs text-muted-foreground">
                {filtered.filter(t => t.staffMember === s.name).length} transactions
              </p>
            </div>
          </motion.div>
        ))}
      </div>
    </div>
  );
}
