import { PageHeader } from "@/components/PageHeader";
import { useTransactions, useStaffMembers, getStaffStats, getToday } from "@/lib/store";
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Cell } from "recharts";
import { motion } from "framer-motion";
import { useMemo, useState } from "react";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Trophy, TrendingUp, Users, Plus, Trash2, X } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { toast } from "sonner";

const COLORS = [
  "hsl(262, 60%, 50%)",
  "hsl(340, 65%, 55%)",
  "hsl(152, 58%, 38%)",
  "hsl(38, 92%, 50%)",
  "hsl(210, 80%, 52%)",
  "hsl(20, 80%, 52%)",
];

function fmt(n: number) {
  return `₹${n.toLocaleString('en-IN')}`;
}

export default function Staff() {
  const { transactions } = useTransactions();
  const { staff, addStaff, removeStaff } = useStaffMembers();
  const today = getToday();
  const [period, setPeriod] = useState<'today' | 'month' | 'all'>('all');
  const [newName, setNewName] = useState("");
  const [showAdd, setShowAdd] = useState(false);

  const filtered = useMemo(() => {
    if (period === 'today') return transactions.filter(t => t.date === today);
    if (period === 'month') {
      const m = today.slice(0, 7);
      return transactions.filter(t => t.date.startsWith(m));
    }
    return transactions;
  }, [transactions, period, today]);

  const stats = useMemo(() => getStaffStats(filtered), [filtered]);
  const totalRevenue = stats.reduce((s, st) => s + st.revenue, 0);

  // Staff with no transactions in this period
  const activeNames = new Set(stats.map(s => s.name));
  const inactiveStaff = staff.filter(s => !activeNames.has(s));

  const handleAdd = () => {
    const trimmed = newName.trim();
    if (!trimmed) return;
    if (staff.includes(trimmed)) { toast.error("Already exists!"); return; }
    addStaff(trimmed);
    setNewName("");
    setShowAdd(false);
    toast.success(`Added ${trimmed}`);
  };

  return (
    <div>
      <PageHeader
        title="Staff Performance"
        description="Track revenue generated by each team member"
        icon={Users}
        actions={
          <Button size="sm" variant="outline" className="gap-2 rounded-xl" onClick={() => setShowAdd(!showAdd)}>
            {showAdd ? <X className="h-3.5 w-3.5" /> : <Plus className="h-3.5 w-3.5" />}
            {showAdd ? "Cancel" : "Add Staff"}
          </Button>
        }
      />

      {showAdd && (
        <motion.div initial={{ opacity: 0, height: 0 }} animate={{ opacity: 1, height: "auto" }} className="card-elevated mb-6 flex gap-3 items-end">
          <div className="flex-1">
            <Input
              placeholder="Enter staff name..."
              value={newName}
              onChange={e => setNewName(e.target.value)}
              onKeyDown={e => e.key === "Enter" && handleAdd()}
              className="rounded-xl h-10"
              autoFocus
            />
          </div>
          <Button onClick={handleAdd} className="rounded-xl h-10">Add</Button>
        </motion.div>
      )}

      <div className="mb-6 flex flex-wrap items-center gap-4">
        <Select value={period} onValueChange={v => setPeriod(v as typeof period)}>
          <SelectTrigger className="w-40 rounded-xl"><SelectValue /></SelectTrigger>
          <SelectContent>
            <SelectItem value="today">Today</SelectItem>
            <SelectItem value="month">This Month</SelectItem>
            <SelectItem value="all">All Time</SelectItem>
          </SelectContent>
        </Select>
        <div className="flex items-center gap-2 rounded-xl bg-primary/8 px-3 py-1.5 text-sm font-medium text-primary">
          <TrendingUp className="h-3.5 w-3.5" />
          Total: {fmt(totalRevenue)}
        </div>
      </div>

      <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} className="card-elevated mb-6">
        <h3 className="section-title mb-5">Revenue by Staff</h3>
        {stats.length === 0 ? (
          <div className="flex h-[200px] items-center justify-center">
            <p className="text-sm text-muted-foreground">No data for this period.</p>
          </div>
        ) : (
          <ResponsiveContainer width="100%" height={Math.max(200, stats.length * 52)}>
            <BarChart data={stats} layout="vertical" margin={{ left: 10 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="hsl(220,13%,91%)" horizontal={false} />
              <XAxis type="number" tick={{ fontSize: 11, fill: 'hsl(220,10%,46%)' }} axisLine={false} tickLine={false} />
              <YAxis type="category" dataKey="name" tick={{ fontSize: 12, fill: 'hsl(224,28%,12%)' }} axisLine={false} tickLine={false} width={70} />
              <Tooltip formatter={(v: number) => fmt(v)} contentStyle={{ borderRadius: 12, border: '1px solid hsl(220,13%,91%)', fontSize: 13 }} />
              <Bar dataKey="revenue" radius={[0, 8, 8, 0]} barSize={24}>
                {stats.map((_, i) => (
                  <Cell key={i} fill={COLORS[i % COLORS.length]} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        )}
      </motion.div>

      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {stats.map((s, i) => (
          <motion.div
            key={s.name}
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: i * 0.04 }}
            className="card-elevated flex items-center gap-4 group"
          >
            <div className="flex h-10 w-10 items-center justify-center rounded-xl" style={{ backgroundColor: `${COLORS[i % COLORS.length]}15` }}>
              {i === 0 ? (
                <Trophy className="h-5 w-5" style={{ color: COLORS[0] }} />
              ) : (
                <span className="text-sm font-bold" style={{ color: COLORS[i % COLORS.length] }}>#{i + 1}</span>
              )}
            </div>
            <div className="flex-1 min-w-0">
              <p className="font-display font-semibold text-foreground truncate">{s.name}</p>
              <p className="text-xs text-muted-foreground">
                {filtered.filter(t => t.staffMember === s.name).length} transactions
              </p>
            </div>
            <p className="text-lg font-bold text-foreground">{fmt(s.revenue)}</p>
            <Button
              variant="ghost"
              size="icon"
              className="h-7 w-7 opacity-0 group-hover:opacity-100 transition-opacity shrink-0"
              onClick={() => { removeStaff(s.name); toast.info(`Removed ${s.name}`); }}
            >
              <Trash2 className="h-3.5 w-3.5 text-destructive" />
            </Button>
          </motion.div>
        ))}

        {/* Inactive staff (no revenue in this period) */}
        {inactiveStaff.map((name) => (
          <motion.div
            key={name}
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            className="card-elevated flex items-center gap-4 group opacity-60"
          >
            <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-muted">
              <span className="text-xs font-bold text-muted-foreground">—</span>
            </div>
            <div className="flex-1 min-w-0">
              <p className="font-display font-semibold text-foreground truncate">{name}</p>
              <p className="text-xs text-muted-foreground">No transactions</p>
            </div>
            <p className="text-lg font-bold text-muted-foreground">₹0</p>
            <Button
              variant="ghost"
              size="icon"
              className="h-7 w-7 opacity-0 group-hover:opacity-100 transition-opacity shrink-0"
              onClick={() => { removeStaff(name); toast.info(`Removed ${name}`); }}
            >
              <Trash2 className="h-3.5 w-3.5 text-destructive" />
            </Button>
          </motion.div>
        ))}
      </div>
    </div>
  );
}
